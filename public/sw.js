/* Minimal service worker: makes the staff app installable and caches only immutable
   static assets. Pages and data are always fetched live, so orders are never stale. */
const CACHE = "smartdine-static-v1";
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin) return;
  const immutable = url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/dishes/") || url.pathname.startsWith("/icons/");
  if (!immutable) return;
  e.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(e.request);
      if (hit) return hit;
      const res = await fetch(e.request);
      if (res.ok) cache.put(e.request, res.clone());
      return res;
    }),
  );
});
